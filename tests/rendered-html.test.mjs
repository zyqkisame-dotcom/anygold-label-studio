import assert from "node:assert/strict";
import test from "node:test";

async function render() {
  const workerUrl = new URL("../dist/server/index.js", import.meta.url);
  workerUrl.searchParams.set("test", `${process.pid}-${Date.now()}`);
  const { default: worker } = await import(workerUrl.href);

  return worker.fetch(
    new Request("http://localhost/", {
      headers: { accept: "text/html" },
    }),
    {
      ASSETS: {
        fetch: async () => new Response("Not found", { status: 404 }),
      },
    },
    {
      waitUntil() {},
      passThroughOnException() {},
    },
  );
}

test("server-renders the ANYGOLD Label Studio dashboard in English", async () => {
  const response = await render();
  assert.equal(response.status, 200);
  assert.match(response.headers.get("content-type") ?? "", /^text\/html\b/i);

  const html = await response.text();
  assert.match(html, /<html lang="en">/i);
  assert.match(html, /<title>ANYGOLD Label Studio<\/title>/i);
  assert.match(html, /Label printing,/i);
  assert.match(html, /Standard label/i);
  assert.match(html, /Custom design/i);
  assert.match(html, /Print quality/i);
  assert.doesNotMatch(html, /Label biasa|Tetapan|Kuantiti|Saiz tag/i);
});
